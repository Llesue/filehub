export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let value = lang === 'en' ? (en[key] ?? key) : key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function localeOf(lang: Lang): string {
  return lang === 'en' ? 'en-US' : 'zh-CN';
}

export function rootAlias(lang: Lang, alias: string): string {
  return alias === '我的文件' || alias === 'My Files' ? t(lang, '我的文件') : alias;
}

export function initLanguage(): void {
  let stored: string | null = null;
  try {
    stored = localStorage.getItem('filehub.lang');
  } catch {
    // ignore
  }
  const languages =
    typeof navigator === 'undefined'
      ? []
      : navigator.languages?.length
        ? navigator.languages
        : [navigator.language];
  const lang: Lang =
    stored === 'en' || stored === 'zh-CN' ? stored : detectBrowserLanguage(languages);
  language.set(lang);
  document.documentElement.lang = lang;
}

export function detectBrowserLanguage(languages: readonly string[] | undefined): Lang {
  const primary = languages?.find((value) => typeof value === 'string' && value.length > 0);
  if (!primary) return 'zh-CN';
  return primary.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function setLanguage(lang: Lang): void {
  language.set(lang);
  document.documentElement.lang = lang;
  try {
    localStorage.setItem('filehub.lang', lang);
  } catch {
    // ignore
  }
}
